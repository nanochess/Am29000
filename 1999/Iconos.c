/*
** Pelotas de la barra de herramientas
*/
extern unsigned short dibujo_pelotas[];  /* El dibujo en 16 bits */
extern char transparencia_pelotas[];     /* Mapa de transparencia */

void prepara_pelotas(void)
{
  char *transparencia;
  unsigned short *ap, val;
  int rojo1, verde1, azul1;
  int rojo, verde, azul;
  int color;
  int pixeles;
  int nivel1, nivel2;

  color = lee_sistema(S_V_COLOR_FONDO);
  rojo1 = (color >> 19) & 0x1f;
  verde1 = (color >> 10) & 0x3f;
  azul1 = (color >> 3) & 0x1f;
  transparencia = transparencia_pelotas;
  ap = dibujo_pelotas;
  for (pixeles = 0; pixeles < 5120; pixeles++) {
    val = *ap;
    nivel1 = *transparencia++;
    nivel2 = (4 - nivel1);
    rojo = ((val >> 11) & 0x1f) * nivel2;
    verde = ((val >> 5) & 0x3f) * nivel2;
    azul = (val & 0x1f) * nivel2;
    rojo = (rojo + (rojo1 * nivel1) + 3) / 4;
    verde = (verde + (verde1 * nivel1) + 3) / 4;
    azul = (azul + (azul1 * nivel1) + 3) / 4;
    *ap++ = (rojo << 11) | (verde << 5) | azul;
  }
}

