/*
** Compara dos cadenas de caracteres
*/
int strcmp(char *a, char *b)
{
  while (1) {
    if (*a != *b) {
      if (*a < *b)
        return -1;
      else
        return 1;
    }
    if (*a++ == '\0')
      return 0;
    b++;
  }
}

/*
** Copia una cadena de wchar_t
*/
void wcscpy(wchar_t *ap1, wchar_t *ap2)
{
  while (*ap1++ = *ap2++) ;
}

/*
** Cálcula la longitud de una cadena de wchar_t
*/
int wcslen(wchar_t *ap1)
{
  wchar_t *ap2 = ap1;

  while (*ap1)
    ap1++;
  return ap1 - ap2;
}

/*
** Convierte una cadena en un entero
*/
int atoi(char *a)
{
  int v = 0;

  while (*a >= '0' && *a <= '9')
    v = v * 10 + *a++ - '0';
  return v;
}

/*
** Convierte un entero a una cadena de texto.
*/
wchar_t *entero_wchar(int numero, wchar_t *texto)
{
  if (numero < 0) {
    *texto++ = '-';
    numero = -numero;
  }
  if (numero >= 10)
    texto = entero_wchar(numero / 10, texto);
  *texto++ = (numero % 10) + '0';
  *texto = 0;
  return texto;
}

/*
** Crea la carpeta por omisión para los documentos HTML
** (debe modificarse por cada programa)
*/
void carpeta_por_omision(wchar_t *buffer)
{
  wchar_t *nombre, *ap;

  /*
  ** Indica al archivero que comience al principio de la carpeta
  */
  *buffer++ = 0;
  *buffer++ = 0;

  /*
  ** Obtiene el camino al ejecutable, de ahí se deriva
  ** la carpeta
  */
  nombre = info_tarea(leer_variable(ventana_interfaz, V_TAREA));
  ap = buffer;
  while (*nombre && *nombre != 1)
    *ap++ = *nombre++;
  while (*--ap != '/') ;
  ap++;
  wcscpy(ap, L"Documentos HTML");
  mkdir(buffer);
  while (*ap)
    ap++;
  wcscpy(ap, L"/Oscar");
}
